"""Declarative base, constraint naming convention and reusable column mixins.

Tenant isolation metadata
-------------------------
Every tenant table declares how Row-Level Security applies to it through ``__table_args__``'s
``info={"rls": ...}`` (use the helpers below). Migrations read it to create the matching policy, and
``alembic/env.py`` adds the policy automatically to autogenerated ``create_table`` migrations.

* ``TENANT_RLS``             – table has its own ``tenant_id`` column
* ``child_rls(fk, parent)``  – table has no ``tenant_id``; rows are visible when their parent row is
* no ``rls`` key             – global table (accounts, routing), never exposed to tenant sessions
"""
import uuid
from datetime import datetime
from sqlalchemy import Column, DateTime, MetaData, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import declarative_base, declared_attr

# Deterministic constraint names so migrations can reference (and drop) them reliably
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_name)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

Base = declarative_base(metadata=MetaData(naming_convention=NAMING_CONVENTION))

TENANT_RLS = {"info": {"rls": "tenant"}}

def child_rls(fk_column: str, parent_table: str) -> dict:
    return {"info": {"rls": "child", "rls_fk": fk_column, "rls_parent": parent_table}}

def uuid_pk() -> Column:
    return Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

def tenant_id_column() -> Column:
    return Column(UUID(as_uuid=True), nullable=False, index=True)

def created_at_column(server_default: bool = True) -> Column:
    if server_default:
        return Column(DateTime, default=datetime.utcnow, server_default=func.now(), nullable=False)
    return Column(DateTime, default=datetime.utcnow, nullable=False)

def updated_at_column() -> Column:
    """Bumped on every change — drives incremental offline sync (/sync/pull)."""
    return Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, server_default=func.now(), nullable=False)

class TenantScoped:
    """Mixin for tables that belong to one business: adds an indexed ``tenant_id``."""

    @declared_attr
    def tenant_id(cls):  # noqa: N805 - SQLAlchemy declared_attr signature
        return tenant_id_column()
