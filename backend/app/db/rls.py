"""Row-Level Security building blocks shared by migrations.

Tenant sessions (``app.core.tenant.get_tenant_db``) switch to the non-superuser role ``tallyko_app`` and set
``app.current_tenant_id``; the policies below make PostgreSQL itself hide other businesses' rows.
RLS is deliberately not FORCEd: system sessions (login, tenant routing, staff management) run as the
table owner and bypass it.

Migrations call the ``op``-based helpers; ``alembic/env.py`` uses the ``*_sql`` builders to add the
same statements to autogenerated ``create_table`` migrations.
"""
TENANT_ROLE = "tallyko_app"
POLICY = "tenant_isolation"
# An unset or empty setting becomes NULL, which matches nothing — so a forgotten setting fails closed
CURRENT_TENANT = "NULLIF(current_setting('app.current_tenant_id', true), '')::uuid"

def create_role_sql() -> list[str]:
    return [
        f"""
        DO $$
        BEGIN
            IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{TENANT_ROLE}') THEN
                CREATE ROLE {TENANT_ROLE} NOLOGIN;
            END IF;
        END
        $$
        """,
        # Lets the app's connecting user SET ROLE to it (needed when that user is not a superuser)
        f"GRANT {TENANT_ROLE} TO CURRENT_USER",
        f"GRANT USAGE ON SCHEMA public TO {TENANT_ROLE}",
    ]

def tenant_policy_sql(table: str) -> list[str]:
    """For tables with their own ``tenant_id`` column."""
    return [
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO {TENANT_ROLE}",
        f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY",
        f"CREATE POLICY {POLICY} ON {table} USING (tenant_id = {CURRENT_TENANT}) WITH CHECK (tenant_id = {CURRENT_TENANT})",
    ]

def child_policy_sql(table: str, fk_column: str, parent_table: str) -> list[str]:
    """For tables without ``tenant_id``: a row is visible when its parent row is (the parent's policy applies)."""
    return [
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO {TENANT_ROLE}",
        f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY",
        f"CREATE POLICY {POLICY} ON {table} USING (EXISTS (SELECT 1 FROM {parent_table} p WHERE p.id = {table}.{fk_column}))",
    ]

def policy_sql_for(table: str, info: dict) -> list[str]:
    """Statements for a table from its model metadata (``__table_args__`` info, see app/models/base.py)."""
    kind = info.get("rls")
    if kind == "tenant":
        return tenant_policy_sql(table)
    if kind == "child":
        return child_policy_sql(table, info["rls_fk"], info["rls_parent"])
    return []

# --- helpers for migration scripts -------------------------------------------------------------------

def _execute(statements: list[str]) -> None:
    from alembic import op
    for statement in statements:
        op.execute(statement)

def create_tenant_role() -> None:
    _execute(create_role_sql())

def enable_tenant_rls(table: str) -> None:
    _execute(tenant_policy_sql(table))

def enable_child_rls(table: str, fk_column: str, parent_table: str) -> None:
    _execute(child_policy_sql(table, fk_column, parent_table))

def disable_rls(table: str) -> None:
    """Undo ``enable_*_rls`` on a table that is kept (dropping a table removes its policy automatically)."""
    _execute([
        f"DROP POLICY IF EXISTS {POLICY} ON {table}",
        f"ALTER TABLE {table} DISABLE ROW LEVEL SECURITY",
        f"REVOKE ALL ON {table} FROM {TENANT_ROLE}",
    ])
